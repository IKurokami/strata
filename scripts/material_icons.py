"""Import the complete Zed Material Icon Theme without modifying its SVGs.

Usage: scripts/material_icons.py <zed-extensions/material-icon-theme checkout>
"""

import json
from pathlib import Path
import shutil
import subprocess
import sys

REPOSITORY = Path(__file__).resolve().parent.parent
PREFIX = "strata-material-"


def icon_name(path):
    name = Path(path).stem
    if not name or name in (".", "..") or not all(character.isascii() and (character.isalnum() or character in "-_.") for character in name):
        raise ValueError(f"invalid icon name: {name}")
    return PREFIX + name


def table(name, entries):
    folded = {}
    for key, value in entries.items():
        lowered = key.lower()
        if lowered in folded and folded[lowered] != value:
            raise ValueError(f"ambiguous case-insensitive association: {key}")
        folded[lowered] = value
    return "const " + name + ": &[(&str, &str)] = &[\n" + "".join(
        f"    ({json.dumps(key, ensure_ascii=False)}, {json.dumps(value)}),\n"
        for key, value in sorted(folded.items())
    ) + "];\n"


def main(upstream):
    theme = json.loads((upstream / "icon_themes/material-icon-theme.json").read_text())["themes"][0]
    definitions = {key: icon_name(value["path"]) for key, value in theme["file_icons"].items()}
    # Upstream associations also reference physical SVG names (git/template)
    # whose semantic definition IDs differ or are absent from file_icons.
    for reference in set(theme["file_stems"].values()) | set(theme["file_suffixes"].values()):
        if reference not in definitions:
            if not (upstream / "icons" / (reference + ".svg")).is_file():
                raise ValueError(f"unresolved icon association: {reference}")
            definitions[reference] = icon_name(reference + ".svg")
    names = {key: definitions[value] for key, value in theme["file_stems"].items()}
    suffixes = {key: definitions[value] for key, value in theme["file_suffixes"].items()}
    folders = {key: icon_name(value["collapsed"]) for key, value in theme["named_directory_icons"].items()}
    module = "// SPDX-License-Identifier: MIT AND Apache-2.0\n// Generated by scripts/material_icons.py; do not edit.\n\n"
    for name, entries in [("FILE_NAMES", names), ("FILE_SUFFIXES", suffixes), ("DIRECTORIES", folders)]:
        module += table(name, entries) + "\n"
    module += '''fn lookup(table: &[(&str, &'static str)], key: &str) -> Option<&'static str> {
    table.binary_search_by(|(candidate, _)| candidate.cmp(&key)).ok().map(|index| table[index].1)
}

pub(crate) fn icon_for_name(name: &str, directory: bool) -> &'static str {
    #[cfg(windows)]
    let name = name.replace('\\\\', "/");
    let lowered = name.to_lowercase();
    let table = if directory { DIRECTORIES } else { FILE_NAMES };
    let starts = std::iter::once(0).chain(lowered.match_indices('/').map(|(index, _)| index + 1));
    for start in starts {
        if let Some(icon) = lookup(table, &lowered[start..]) {
            return icon;
        }
    }
    if directory {
        return "strata-material-folder";
    }
    let filename = lowered.rsplit('/').next().unwrap_or(&lowered);
    for (index, _) in filename.match_indices('.') {
        if let Some(icon) = lookup(FILE_SUFFIXES, &filename[index + 1..]) {
            return icon;
        }
    }
    "strata-material-file"
}

#[cfg(test)]
mod tests;
'''
    destination = REPOSITORY / "data/icons/material"
    destination.mkdir(exist_ok=True)
    resources = []
    for source in sorted((upstream / "icons").glob("*.svg")):
        target = destination / (icon_name(source.name) + ".svg")
        if not target.is_file() or target.read_bytes() != source.read_bytes():
            shutil.copyfile(source, target)
        resources.append("    <file>icons/material/" + target.name + "</file>\n")
    available = {path.stem for path in destination.glob("*.svg")}
    for reference in list(definitions.values()) + list(folders.values()):
        if reference not in available:
            raise ValueError(f"missing icon: {reference}")
    (REPOSITORY / "src/material_icons.rs").write_text(module)
    subprocess.run(["rustfmt", "--edition", "2024", str(REPOSITORY / "src/material_icons.rs")], check=True)
    resource_file = REPOSITORY / "data/strata.gresource.xml"
    text = "".join(line for line in resource_file.read_text().splitlines(keepends=True) if "<file>icons/material/" not in line)
    resource_file.write_text(text.replace("  </gresource>", "".join(resources) + "  </gresource>"))
    print(f"Imported {len(resources)} icons, {len(names)} filename associations, {len(suffixes)} suffixes, {len(folders)} directory associations")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
